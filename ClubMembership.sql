DROP DATABASE IF EXISTS ClubMembership;
CREATE DATABASE ClubMembership;
USE ClubMembership;

CREATE TABLE Students (
    StudentID INT PRIMARY KEY,
    FirstName VARCHAR(50) NOT NULL,
    LastName VARCHAR(50) NOT NULL,
    Email VARCHAR(100) NOT NULL UNIQUE,
    Major VARCHAR(50),
    ClassYear VARCHAR(10) NOT NULL,
    INDEX idx_student_major (Major)
);

CREATE TABLE Clubs (
    ClubID INT PRIMARY KEY,
    ClubName VARCHAR(50) NOT NULL,
    Description VARCHAR(255),
    MeetingDay VARCHAR(15),
    MeetingLocation VARCHAR(100)
);

CREATE TABLE Memberships (
    StudentID INT NOT NULL,
    ClubID INT NOT NULL,
    JoinDate DATE NOT NULL,
    Position VARCHAR(30) NOT NULL DEFAULT 'Member',
    PRIMARY KEY (StudentID, ClubID),
    FOREIGN KEY (StudentID) REFERENCES Student(StudentID),
    FOREIGN KEY (ClubID) REFERENCES Club(ClubID),
    INDEX idx_membership_club (ClubID)
);

